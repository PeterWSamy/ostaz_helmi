function toPaths(rows) {
  const out = { body: '', inner: '' }
  rows.forEach((raw, y) => {
    const row = raw.length === 12 ? raw + [...raw].reverse().join('') : raw
    let x = 0
    while (x < row.length) {
      const c = row[x]
      let end = x
      while (row[end + 1] === c) end++
      const key = c === '#' ? 'body' : c === 'o' ? 'inner' : null
      if (key) out[key] += `M${x * 2} ${y * 2}h${(end - x + 1) * 2}v2h${-(end - x + 1) * 2}z`
      x = end + 1
    }
  })
  return out
}

export const EMBLEMS = Object.fromEntries(Object.entries(GRIDS).map(([k, v]) => [k, toPaths(v)]))

